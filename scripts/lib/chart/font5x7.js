const GLYPH_W = 5;
const GLYPH_H = 7;
const SPACING = 1;

function glyph(ch) {
  const c = String(ch).toUpperCase();
  return F[c] || F[' '];
}

// 문자열의 픽셀 폭 (scale 배율 적용)
function textWidth(s, scale = 1) {
  const n = String(s).length;
  if (!n) return 0;
  return (n * GLYPH_W + (n - 1) * SPACING) * scale;
}

